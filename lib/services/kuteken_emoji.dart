final RegExp _kutekenPattern = _buildKutekenPattern();

RegExp _buildKutekenPattern() {
  final keys = kutekanEmojiAssets.keys.toList()
    ..sort((a, b) => b.length.compareTo(a.length));
  return RegExp(keys.map(RegExp.escape).join('|'), unicode: true);
}

String normalizeKutekenEmoji(String text) => text.replaceAll('\uFE0F', '');

bool hasKutekenEmoji(String text) =>
    _kutekenPattern.hasMatch(normalizeKutekenEmoji(text));

String? kutekenAssetFor(String emoji) =>
    kutekanEmojiAssets[normalizeKutekenEmoji(emoji)];

class KutekenEmoji extends StatelessWidget {
  const KutekenEmoji(
    this.emoji, {
    super.key,
    this.size = 20,
    this.fallbackStyle,
  });

  final String emoji;
  final double size;
  final TextStyle? fallbackStyle;

  @override
  Widget build(BuildContext context) {
    final asset = kutekenAssetFor(emoji);
    if (asset == null) {
      return Text(
        emoji,
        style: (fallbackStyle ?? const TextStyle()).copyWith(fontSize: size),
      );
    }
    return Image.asset(
      asset,
      width: size,
      height: size,
      filterQuality: FilterQuality.none,
      isAntiAlias: false,
      semanticLabel: emoji,
    );
  }
}

class KutekanEmojiText extends StatelessWidget {
  const KutekanEmojiText(
    this.text, {
    super.key,
    this.style,
    this.maxLines,
    this.overflow = TextOverflow.clip,
    this.textAlign = TextAlign.start,
  });

  final String text;
  final TextStyle? style;
  final int? maxLines;
  final TextOverflow overflow;
  final TextAlign textAlign;

  static const int _maxInlineImages = 50;

  @override
  Widget build(BuildContext context) {
    final normalized = normalizeKutekenEmoji(text);
    if (!_kutekenPattern.hasMatch(normalized)) {
      return Text(
        normalized,
        style: style,
        maxLines: maxLines,
        overflow: overflow,
        textAlign: textAlign,
      );
    }

    final fontSize =
        style?.fontSize ?? DefaultTextStyle.of(context).style.fontSize ?? 16;
    final emojiSize = fontSize * 1.18;
    final spans = <InlineSpan>[];
    var start = 0;
    var images = 0;

    void addText(int end) {
      if (end > start) {
        spans.add(TextSpan(text: normalized.substring(start, end)));
      }
    }

    for (final match in _kutekenPattern.allMatches(normalized)) {
      if (match.start < start) continue;
      final emoji = match.group(0)!;
      final next = match.end < normalized.length
          ? normalized.codeUnitAt(match.end)
          : -1;
      final previous = match.start > 0
          ? normalized.codeUnitAt(match.start - 1)
          : -1;
      final partialSequence =
          previous == 0x200D ||
          next == 0x200D ||
          next == 0x20E3 ||
          (next >= 0x1F3FB && next <= 0x1F3FF);

      addText(match.start);
      if (partialSequence || images >= _maxInlineImages) {
        spans.add(TextSpan(text: emoji));
      } else {
        spans.add(
          WidgetSpan(
            alignment: PlaceholderAlignment.middle,
            child: KutekenEmoji(emoji, size: emojiSize),
          ),
        );
        images++;
      }
      start = match.end;
    }
    addText(normalized.length);

    return Text.rich(
      TextSpan(style: style, children: spans),
      maxLines: maxLines,
      overflow: overflow,
      textAlign: textAlign,
    );
  }
}
