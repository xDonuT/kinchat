#!/usr/bin/env bash
#
# Creates the Flutter project, adds the Firebase packages, and drops in the
# KinChat source. Run this once, on the computer that has Flutter installed.
#
#   bash bootstrap.sh
#
set -euo pipefail

SRC="$(cd "$(dirname "$0")" && pwd)"
APP=kinchat
ORG=com.kinchat

command -v flutter >/dev/null 2>&1 || {
  echo "flutter is not on your PATH. Install it from https://docs.flutter.dev/get-started/install"
  exit 1
}

echo "==> Creating Flutter project: $APP"
if [ -d "$APP" ]; then
  echo "    $APP already exists. Delete it first:  rm -rf $APP"
  exit 1
fi
flutter create --org "$ORG" --project-name "$APP" --platforms android "$APP"

cd "$APP"

echo "==> Adding dependencies"
flutter pub add firebase_core firebase_auth cloud_firestore intl

echo "==> Copying KinChat source"
cp -r "$SRC/lib/." lib/

if [ -d "$SRC/integration_test" ]; then
  mkdir -p integration_test
  cp -r "$SRC/integration_test/." integration_test/
fi
if [ -d "$SRC/tests" ]; then
  mkdir -p tests
  cp -r "$SRC/tests/." tests/
fi
for f in firestore.rules firestore.rules.dev firebase.json firebase.dev.json \
         run-emulator.sh run-e2e.sh README.md; do
  [ -e "$SRC/$f" ] && cp "$SRC/$f" .
done
chmod +x run-emulator.sh run-e2e.sh 2>/dev/null || true

# The onboarding widget_test generated by flutter create does not apply here.
rm -f test/widget_test.dart

echo "==> Patching AndroidManifest"
MANIFEST=android/app/src/main/AndroidManifest.xml

# Flutter only puts the INTERNET permission in the debug manifest. A release
# APK without it cannot reach Firebase at all.
if ! grep -q 'android.permission.INTERNET' "$MANIFEST"; then
  python3 - "$MANIFEST" <<'PY'
import sys
path = sys.argv[1]
with open(path) as f:
    text = f.read()
text = text.replace(
    '<application',
    '<uses-permission android:name="android.permission.INTERNET"/>\n    <application',
    1,
)
with open(path, 'w') as f:
    f.write(text)
print("    + INTERNET permission")
PY
fi

# Firebase emulators speak plain HTTP, which Android 9+ blocks. Allow it only
# for the emulator's host aliases; production stays HTTPS-only.
NETWORK_DIR=android/app/src/main/res/xml
mkdir -p "$NETWORK_DIR"
cat > "$NETWORK_DIR/network_security_config.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<network-security-config>
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">10.0.2.2</domain>
        <domain includeSubdomains="false">10.0.3.2</domain>
        <domain includeSubdomains="false">localhost</domain>
        <domain includeSubdomains="false">127.0.0.1</domain>
    </domain-config>
    <base-config cleartextTrafficPermitted="false" />
</network-security-config>
XML
if ! grep -q 'networkSecurityConfig' "$MANIFEST"; then
  python3 - "$MANIFEST" <<'PY'
import sys
path = sys.argv[1]
with open(path) as f:
    text = f.read()
text = text.replace(
    'android:icon="@mipmap/ic_launcher"',
    'android:icon="@mipmap/ic_launcher"\n        android:networkSecurityConfig="@xml/network_security_config"',
    1,
)
with open(path, 'w') as f:
    f.write(text)
print("    + network security config (allows HTTP to the emulator only)")
PY
fi

echo
echo "==> Project ready at: $(pwd)"
cat <<'MSG'

Quick way to see it working (no Firebase project needed):

    ./run-emulator.sh        # starts emulators + runs the app on your phone
                              # look for the yellow TEST MODE stripe

To put it on your nephew's phone, use the real project instead:

    1. console.firebase.google.com -> Add project (e.g. kinchat-c9057)
    2. Add an Android app, package name: com.kinchat.kinchat
    3. Authentication -> Sign-in method -> Email/Password -> Enable
    4. Firestore Database -> Create database -> production mode
    5. dart pub global activate flutterfire_cli
       flutterfire configure --project=kinchat-c9057
    6. npm install -g firebase-tools && firebase login
       firebase use --add
       flutter build apk --debug --split-per-abi

See README.md for the full walkthrough, including getting the two UIDs
into firestore.rules before anyone can log in.
MSG